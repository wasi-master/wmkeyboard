/**
 * What the reply panel calls back into.
 *
 * One bundle rather than a dozen parameters, for the reason
 * [CaptureCallbacks] is one: `ServiceKeyboardContent` sits against the JVM's
 * 64K method-size ceiling and every parameter costs generated bytecode there.
 */
data class ReplyCallbacks(
    val onAddClip: () -> Unit = {},
    val onAddSelection: () -> Unit = {},
    val onTypeFocus: (Boolean) -> Unit = {},
    val onTypedDone: () -> Unit = {},
    val onToggleSide: (Int) -> Unit = {},
    val onRemove: (Int) -> Unit = {},
    val onClear: () -> Unit = {},
    val onTidyUp: (Boolean) -> Unit = {},
    val onPickShots: (Boolean) -> Unit = {},
    val onAddShot: (String) -> Unit = {},
    val onTone: (AiActionSpec) -> Unit = {},
    val onInsert: (String) -> Unit = {},
    /** Joins a message to the one before it: one bubble OCR read as two. */
    val onMerge: (Int) -> Unit = {},
    /** Back from the drafts to the gathered messages. */
    val onShowMessages: () -> Unit = {},
    /** The images permission, through the trampoline. */
    val onAllowImages: () -> Unit = {},
    /** The model chip row: the AI tool's own picker, the same shared choice. */
    val onPickModel: (AiProvider, String?) -> Unit = { _, _ -> },
    /** Screenshots go to the model as the picture (true) or as the text read off it (false). */
    val onSendPictures: (Boolean) -> Unit = {},
    /** Opens a message in the message box to fix it. */
    val onEdit: (Int) -> Unit = {},
    /** Clears every message marked as having no real words. */
    val onRemoveUnclear: () -> Unit = {},
)

/**
 * The AI reply tool (#234).
 *
 * Three steps, top to bottom, and the panel only ever shows the ones that
 * apply: the ways to add what the other person said, the conversation
 * gathered so far (or the drafts, once there are some), and the tones to
 * answer in. The first step is the one that makes this tool different from
 * every other AI surface — the keyboard cannot read the conversation it is
 * replying to, so gathering it is a thing the user does, and the panel is
 * mostly about making that cheap.
 */
@OptIn(ExperimentalLayoutApi::class)
@Composable
internal fun AiReplyPanel(
    state: KeyboardUiState,
    callbacks: ReplyCallbacks,
    onOpenToolSettings: (ToolbarTool) -> Unit,
) {
    val kb = LocalKbTheme.current
    val reply = state.aiReply
    val tones = visibleAiActions(
        state.settings.ai.customActions,
        state.settings.ai.actionOrder,
        state.settings.ai.hiddenActions,
        AiActionSurface.REPLY,
    )
    // The AI tool's model row, word for word: the choice is shared, so
    // switching here switches there. Hidden while a run is going — changing
    // the model under a request in flight would only cancel it.
    val picks = if (state.settings.ai.panelModelPicker && state.ai !is AiUi.Loading) {
        rememberModelPicks(state, callbacks.onPickModel)
    } else {
        emptyList()
    }
    Column(
        modifier = Modifier
            .fillMaxSize()
            .padding(horizontal = 8.dp, vertical = 4.dp),
    ) {
        if (picks.isNotEmpty() && !reply.picking) ModelPickerRow(picks)
        when (val ai = state.ai) {
            // The provider screens are the AI tool's, word for word: the same
            // setup is missing and the same page fixes it.
            AiUi.NeedSetup, AiUi.NeedModel -> ReplyCentredNotice(
                text = stringResource(
                    if (ai == AiUi.NeedModel) R.string.ime_ai_need_model_body
                    else R.string.ime_ai_setup_body,
                ),
                action = stringResource(R.string.ime_ai_open_settings_action),
                onAction = { onOpenToolSettings(ToolbarTool.AI) },
            )
            // Drafts stream in: once the first one has arrived the panel
            // shows them under a thin bar rather than the full loader.
            is AiUi.Loading -> if (reply.candidates.isEmpty()) {
                ReplyLoading(ai)
            } else {
                LinearProgressIndicator(
                    progress = { ai.phase.fraction },
                    color = kb.accent,
                    modifier = Modifier.fillMaxWidth().height(2.dp),
                )
                Spacer(Modifier.height(4.dp))
                Box(Modifier.weight(1f).fillMaxWidth()) { ReplyDrafts(state, callbacks) }
            }
            is AiUi.Error -> ReplyCentredNotice(
                text = ai.message,
                action = stringResource(CommonR.string.common_retry),
                onAction = { reply.tone?.let(callbacks.onTone) },
            )
            else -> {
                if (reply.picking) {
                    ReplyShotPicker(state, callbacks)
                } else {
                    ReplyGather(state, callbacks)
                    // The middle takes what is left, so the tones below stay
                    // on screen however long the conversation gets — they are
                    // the next step, and a list that pushes them off the
                    // bottom leaves the user with nothing to press.
                    Box(
                        Modifier
                            .weight(1f)
                            .fillMaxWidth()
                            .padding(vertical = 4.dp),
                    ) {
                        when {
                            reply.candidates.isNotEmpty() -> ReplyDrafts(state, callbacks)
                            reply.entries.isNotEmpty() -> ReplyConversation(state, callbacks)
                            else -> ReplyEmpty()
                        }
                    }
                    // How a screenshot reaches the model, where there is one:
                    // the picture itself, or the text read off it on the phone.
                    if (reply.hasShots && reply.candidates.isEmpty()) {
                        ReplySendAsRow(
                            pictures = reply.entries.any { it.image },
                            canSendPicture = reply.canSendPicture,
                            onSendPictures = callbacks.onSendPictures,
                        )
                    }
                    // The run writes from what the user had started, and the
                    // reply they pick replaces it: say so before they pick a
                    // tone, so the drafts saying their words is no surprise.
                    if (reply.draft.isNotBlank()) {
                        Text(
                            stringResource(R.string.ime_reply_draft_line, reply.draft),
                            color = kb.secondaryText,
                            fontSize = 11.sp,
                            maxLines = 1,
                            overflow = androidx.compose.ui.text.style.TextOverflow.Ellipsis,
                            modifier = Modifier.padding(horizontal = 4.dp, vertical = 2.dp),
                        )
                    }
                    if (reply.hasContext) {
                        ReplyToneRow(
                            tones,
                            again = reply.candidates.isNotEmpty(),
                            current = reply.tone?.id,
                            onTone = callbacks.onTone,
                        )
                    }
                }
            }
        }
    }
}

/** The ways to add to the conversation, and what is happening to them. */
@OptIn(ExperimentalLayoutApi::class)
@Composable
private fun ReplyGather(state: KeyboardUiState, callbacks: ReplyCallbacks) {
    val kb = LocalKbTheme.current
    val reply = state.aiReply
    // Words, not icons: a clipboard, a plus and a phone outline say nothing
    // about which one reads a screenshot, and this row is the first thing
    // anybody new to the tool has to understand.
    // One line that scrolls sideways rather than a row that wraps: every line
    // this row grows by comes out of the conversation's share of the panel.
    Row(
        modifier = Modifier.fillMaxWidth().horizontalScroll(rememberScrollState()),
        horizontalArrangement = Arrangement.spacedBy(5.dp),
        verticalAlignment = Alignment.CenterVertically,
    ) {
        // First in the row while there are any: the one tap that clears what
        // OCR or a stray copy left that is not a message at all.
        if (reply.unclearCount > 0) {
            ToolPanelChip(stringResource(R.string.ime_reply_remove_unclear, reply.unclearCount), selected = true) {
                callbacks.onRemoveUnclear()
            }
        }
        ToolPanelChip(stringResource(R.string.ime_reply_add_clip)) { callbacks.onAddClip() }
        ToolPanelChip(stringResource(R.string.ime_reply_add_shot)) { callbacks.onPickShots(true) }
        if (state.screenCapture) {
            val capture = LocalScreenCapture.current
            ToolPanelChip(stringResource(R.string.ime_reply_capture_screen)) { capture(ScreenCaptureTarget.REPLY) }
        }
        ToolPanelChip(stringResource(R.string.ime_reply_add_typed), selected = reply.typing) {
            callbacks.onTypeFocus(!reply.typing)
        }
        // Only where there is a selection to take: in most chat apps the
        // conversation cannot be selected at all, and a chip that is always
        // "nothing selected" is a chip nobody presses twice. An offer with no
        // text is a bare caret's (#763) or one the keyboard did not read.
        if (state.selectionMacros?.text?.isNotEmpty() == true) {
            ToolPanelChip(stringResource(R.string.ime_reply_add_selection)) {
                callbacks.onAddSelection()
            }
        }
        if (reply.entries.isNotEmpty()) {
            ToolPanelChip(stringResource(CommonR.string.common_clear)) { callbacks.onClear() }
        }
    }
    reply.notice?.let { notice ->
        Spacer(Modifier.height(4.dp))
        Row(verticalAlignment = Alignment.CenterVertically) {
            Text(
                stringResource(notice),
                color = kb.secondaryText,
                fontSize = 11.sp,
                modifier = Modifier.weight(1f),
            )
            // The one notice the user can fix from here.
            if (notice == R.string.ime_reply_notice_no_images_permission) {
                Spacer(Modifier.width(6.dp))
                ToolPanelChip(stringResource(R.string.ime_reply_allow_images), selected = true) {
                    callbacks.onAllowImages()
                }
            }
        }
    }
    if (reply.typing) {
        Spacer(Modifier.height(4.dp))
        Row(
            modifier = Modifier
                .fillMaxWidth()
                .clip(RoundedCornerShape(10.dp))
                .frostGlass(kb, RoundedCornerShape(10.dp), FrostSurface.CHIPS)
                .background(kb.chip)
                .padding(horizontal = 8.dp, vertical = 6.dp),
            verticalAlignment = Alignment.CenterVertically,
        ) {
            SearchQueryText(
                query = reply.typed,
                // One box, three jobs: a new message, an edit of one, or the
                // instruction a Custom… tone asks for.
                placeholder = when {
                    reply.askTone != null -> stringResource(R.string.ime_reply_instruction_hint)
                    reply.editing != null -> stringResource(R.string.ime_reply_edit_hint)
                    else -> stringResource(R.string.ime_reply_typed_hint)
                },
                active = state.aiReplyTypingActive,
                textColor = kb.suggestionText,
                placeholderColor = kb.secondaryText,
                fontSize = 13.sp,
                modifier = Modifier.weight(1f),
            )
            Spacer(Modifier.width(6.dp))
            ToolPanelChip(
                stringResource(
                    when {
                        reply.askTone != null -> R.string.ime_reply_write
                        reply.editing != null -> R.string.ime_reply_save
                        else -> R.string.ime_reply_add
                    },
                ),
                selected = true,
            ) {
                callbacks.onTypedDone()
            }
        }
    }
    if (reply.reading) {
        Spacer(Modifier.height(4.dp))
        Text(stringResource(R.string.ime_reply_reading), color = kb.secondaryText, fontSize = 11.sp)
        LinearProgressIndicator(color = kb.accent, modifier = Modifier.fillMaxWidth().height(2.dp))
    }
}

