import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.tasks.InputFile
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction

/**
 * Writes `FeatureModules.kt` for the `wmkeyboard.feature-modules` convention:
 * the object in :core:common with one `ModuleGate` property per gate of
 * native/gates.json that has a `property`, plus the name-keyed views
 * NativeDelivery and :app's `installOnDemandDelivery` wire them through. The
 * hand-written half (the gate types, the library loader) is beside it in
 * core/common/.../modules/FeatureModules.kt.
 */
abstract class FeatureModulesTask : DefaultTask() {

    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val table: RegularFileProperty

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun write() {
        val gates = NativeGates.read(table.get().asFile).gates.filter { it.property != null }
        val out = outputDir.get().asFile.resolve("com/wasimaster/wmkeyboard/core/modules")
        out.mkdirs()
        out.resolve("FeatureModules.kt").writeText(source(gates))
    }

    private fun source(gates: List<NativeGates.Gate>): String = buildString {
        appendLine("// Generated by the wmkeyboard.feature-modules convention from native/gates.json.")
        appendLine("// Do not edit: add or change a gate there.")
        appendLine("package com.wasimaster.wmkeyboard.core.modules")
        appendLine()
        appendLine("import com.wasimaster.wmkeyboard.config.BuildConfig")
        appendLine()
        appendLine("/**")
        appendLine(" * The on-demand modules, one gate each. A `var` per module rather than a map")
        appendLine(" * keyed by name so that a facade cannot ask for a module that does not exist;")
        appendLine(" * the name-keyed [set] is for the code that installs the gates.")
        appendLine(" */")
        appendLine("object FeatureModules {")
        for (gate in gates) {
            appendLine()
            gate.doc?.let { appendLine(kdoc(it, "    ")) }
            appendLine("    @Volatile")
            appendLine("    var ${gate.property}: ModuleGate = AlwaysInstalled")
        }
        appendLine()
        appendLine("    /** Every gate above by its name: its pins.tsv gate and its Play module. */")
        appendLine("    val names: List<String> = listOf(${gates.joinToString { "\"${it.id}\"" }})")
        appendLine()
        appendLine("    /**")
        appendLine("     * The Play modules this build's bundle carries, of the gates above:")
        appendLine("     * every one with a Play module, less those this build switched off.")
        appendLine("     */")
        val play = gates.filter { it.play != null }
        val always = play.filter { it.enabledBy == null }.joinToString { "\"${it.id}\"" }
        val gated = play.filter { it.enabledBy != null }.joinToString { "\"${it.id}\".takeIf { BuildConfig.${it.enabledBy!!.buildConfig} }" }
        appendLine("    val playModules: List<String>")
        appendLine("        get() = listOf($always)" + if (gated.isEmpty()) "" else " + listOfNotNull($gated)")
        appendLine()
        appendLine("    /** The gates of runtimes built on Google's SDKs, which F-Droid's build has none of. */")
        appendLine("    val googleRuntimes: List<String> = listOf(${gates.filter { it.google }.joinToString { "\"${it.id}\"" }})")
        appendLine()
        appendLine("    /** Puts [gate] behind the module [name]. False when no property above has that name. */")
        appendLine("    fun set(name: String, gate: ModuleGate): Boolean {")
        appendLine("        when (name) {")
        for (gate in gates) appendLine("            \"${gate.id}\" -> ${gate.property} = gate")
        appendLine("            else -> return false")
        appendLine("        }")
        appendLine("        return true")
        appendLine("    }")
        appendLine()
        appendLine("    /** The gate behind the module [name], or null when no property above has that name. */")
        appendLine("    fun gate(name: String): ModuleGate? = when (name) {")
        for (gate in gates) appendLine("        \"${gate.id}\" -> ${gate.property}")
        appendLine("        else -> null")
        appendLine("    }")
        appendLine()
        appendLine("    /** See [ModuleLoading.loadLibrary]. */")
        appendLine("    var loadLibrary: (String) -> Unit")
        appendLine("        get() = ModuleLoading.loadLibrary")
        appendLine("        set(value) {")
        appendLine("            ModuleLoading.loadLibrary = value")
        appendLine("        }")
        appendLine()
        appendLine("    /** See [ModuleLoading.awaitInstalled]. */")
        appendLine("    suspend fun ModuleGate.awaitInstalled(onProgress: (bytes: Long, totalBytes: Long) -> Unit = { _, _ -> }): Boolean =")
        appendLine("        ModuleLoading.awaitInstalled(this, onProgress)")
        appendLine()
        appendLine("    /** See [ModuleLoading.load]. */")
        appendLine("    fun <T> load(className: String, loader: ClassLoader): T = ModuleLoading.load(className, loader)")
        appendLine("}")
    }

    /** [text] as a KDoc block, wrapped at 80 columns. */
    private fun kdoc(text: String, indent: String): String {
        val width = 80 - indent.length - 3
        val lines = ArrayList<String>()
        var line = StringBuilder()
        for (word in text.split(' ')) {
            if (line.isNotEmpty() && line.length + 1 + word.length > width) {
                lines += line.toString()
                line = StringBuilder()
            }
            if (line.isNotEmpty()) line.append(' ')
            line.append(word)
        }
        if (line.isNotEmpty()) lines += line.toString()
        return if (lines.size == 1 && indent.length + 7 + lines[0].length <= 100) {
            "$indent/** ${lines[0]} */"
        } else {
            (listOf("$indent/**") + lines.map { "$indent * $it" } + "$indent */").joinToString("\n")
        }
    }
}
