/** Android's DateUtils.getRelativeTimeSpanString with a minute's resolution, in English. */
export function relativeTime(at: number, now = Date.now()): string {
	const diff = now - at;
	const past = diff >= 0;
	const abs = Math.abs(diff);
	const minute = 60_000;
	const hour = 60 * minute;
	const day = 24 * hour;
	if (abs < minute) return past ? '0 minutes ago' : 'in 0 minutes';
	let n: number;
	let unit: string;
	if (abs < hour) {
		n = Math.floor(abs / minute);
		unit = 'minute';
	} else if (abs < day) {
		n = Math.floor(abs / hour);
		unit = 'hour';
	} else if (abs < 7 * day) {
		n = Math.floor(abs / day);
		unit = 'day';
	} else {
		return new Date(at).toLocaleDateString();
	}
	const words = `${n} ${unit}${n === 1 ? '' : 's'}`;
	return past ? `${words} ago` : `in ${words}`;
}
