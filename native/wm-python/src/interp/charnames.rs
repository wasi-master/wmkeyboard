/// The names made by pattern: letters, digits, Greek, Latin-1 and Latin Extended-A letters.
fn generated() -> impl Iterator<Item = (String, char)> {
    let ascii = (0..26u32).flat_map(|i| {
        let l = (b'A' + i as u8) as char;
        [(format!("LATIN CAPITAL LETTER {l}"), 0x41 + i), (format!("LATIN SMALL LETTER {l}"), 0x61 + i)]
    });
    let digits = DIGITS.iter().enumerate().map(|(i, d)| (format!("DIGIT {d}"), 0x30 + i as u32));
    let greek = GREEK.iter().enumerate().filter(|(_, g)| !g.is_empty()).flat_map(|(i, g)| {
        [(format!("GREEK CAPITAL LETTER {g}"), 0x391 + i as u32), (format!("GREEK SMALL LETTER {g}"), 0x3B1 + i as u32)]
    });
    let latin1 = LATIN1.iter().enumerate().filter(|(_, n)| !n.is_empty()).flat_map(|(i, n)| {
        [(format!("LATIN CAPITAL LETTER {n}"), 0xC0 + i as u32), (format!("LATIN SMALL LETTER {n}"), 0xE0 + i as u32)]
    });
    let latin_a = LATIN_A.iter().enumerate().flat_map(|(i, n)| {
        [(format!("LATIN CAPITAL LETTER {n}"), 0x100 + 2 * i as u32), (format!("LATIN SMALL LETTER {n}"), 0x101 + 2 * i as u32)]
    });
    let pairs = LATIN_A_REST.iter().flat_map(|(n, code)| {
        [(format!("LATIN CAPITAL LETTER {n}"), *code), (format!("LATIN SMALL LETTER {n}"), *code + 1)]
    });
    ascii
        .chain(digits)
        .chain(greek)
        .chain(latin1)
        .chain(latin_a)
        .chain(pairs)
        .filter_map(|(n, c)| char::from_u32(c).map(|c| (n, c)))
}

