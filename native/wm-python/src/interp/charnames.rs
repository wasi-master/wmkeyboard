//! Unicode character names for `\N{...}` escapes and `unicodedata.name` and
//! `lookup`: the ones code is likely to write (ASCII, Latin-1, Latin
//! Extended-A, Greek, punctuation, currency, arrows, mathematics, box
//! drawing, shapes, common symbols and emoji), the formal aliases Python
//! accepts (`NBSP`, `ESC`, `BOM`), and the names Unicode builds by rule:
//! CJK unified ideographs, Hangul syllables, variation selectors and
//! regional indicators. Unicode's full table, about 1.8 MB, is not carried.

/// The character [name] names, as `\N{name}` reads it: case does not matter.
pub(crate) fn lookup(name: &str) -> Option<char> {
    let upper = name.trim().to_ascii_uppercase();
    let upper = upper.as_str();
    if let Some(c) = by_rule(upper) {
        return Some(c);
    }
    NAMES
        .iter()
        .chain(ALIASES)
        .find(|(n, _)| *n == upper)
        .and_then(|(_, c)| char::from_u32(*c))
        .or_else(|| generated().find(|(n, _)| n == upper).map(|(_, c)| c))
}

/// The Unicode name of [c], when this table has it.
pub(crate) fn name_of(c: char) -> Option<String> {
    let code = c as u32;
    if let Some(n) = rule_name(code) {
        return Some(n);
    }
    if let Some((n, _)) = NAMES.iter().find(|(_, v)| *v == code) {
        return Some((*n).to_string());
    }
    generated().find(|(_, v)| *v == c).map(|(n, _)| n)
}

