/// Names Unicode builds from the code point.
fn rule_name(code: u32) -> Option<String> {
    if CJK.iter().any(|(a, b)| (*a..=*b).contains(&code)) {
        return Some(format!("CJK UNIFIED IDEOGRAPH-{code:04X}"));
    }
    if (0xAC00..=0xD7A3).contains(&code) {
        let s = code - 0xAC00;
        let (l, v, t) = (s / (21 * 28), (s % (21 * 28)) / 28, s % 28);
        return Some(format!("HANGUL SYLLABLE {}{}{}", JAMO_L[l as usize], JAMO_V[v as usize], JAMO_T[t as usize]));
    }
    if (0xFE00..=0xFE0F).contains(&code) {
        return Some(format!("VARIATION SELECTOR-{}", code - 0xFE00 + 1));
    }
    if (0xE0100..=0xE01EF).contains(&code) {
        return Some(format!("VARIATION SELECTOR-{}", code - 0xE0100 + 17));
    }
    if (0x1F1E6..=0x1F1FF).contains(&code) {
        return Some(format!("REGIONAL INDICATOR SYMBOL LETTER {}", (b'A' + (code - 0x1F1E6) as u8) as char));
    }
    None
}

fn by_rule(upper: &str) -> Option<char> {
    if let Some(hex) = upper.strip_prefix("CJK UNIFIED IDEOGRAPH-") {
        let code = u32::from_str_radix(hex, 16).ok()?;
        return CJK.iter().any(|(a, b)| (*a..=*b).contains(&code)).then(|| char::from_u32(code)).flatten();
    }
    if let Some(rest) = upper.strip_prefix("HANGUL SYLLABLE ") {
        return (0xAC00..=0xD7A3u32).filter_map(char::from_u32).find(|c| rule_name(*c as u32).is_some_and(|n| n[16..] == *rest));
    }
    if let Some(n) = upper.strip_prefix("VARIATION SELECTOR-") {
        let n: u32 = n.parse().ok()?;
        return match n {
            1..=16 => char::from_u32(0xFE00 + n - 1),
            17..=256 => char::from_u32(0xE0100 + n - 17),
            _ => None,
        };
    }
    if let Some(l) = upper.strip_prefix("REGIONAL INDICATOR SYMBOL LETTER ") {
        let b = l.as_bytes();
        return (b.len() == 1 && b[0].is_ascii_uppercase()).then(|| char::from_u32(0x1F1E6 + (b[0] - b'A') as u32)).flatten();
    }
    None
}

