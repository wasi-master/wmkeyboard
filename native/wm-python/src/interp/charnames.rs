#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_round_trip() {
        for (c, name) in [
            ('é', "LATIN SMALL LETTER E WITH ACUTE"),
            ('Ā', "LATIN CAPITAL LETTER A WITH MACRON"),
            ('ł', "LATIN SMALL LETTER L WITH STROKE"),
            ('μ', "GREEK SMALL LETTER MU"),
            ('ς', "GREEK SMALL LETTER FINAL SIGMA"),
            ('—', "EM DASH"),
            ('中', "CJK UNIFIED IDEOGRAPH-4E2D"),
            ('한', "HANGUL SYLLABLE HAN"),
            ('\u{FE0F}', "VARIATION SELECTOR-16"),
            ('7', "DIGIT SEVEN"),
            ('Ω', "GREEK CAPITAL LETTER OMEGA"),
        ] {
            assert_eq!(name_of(c).as_deref(), Some(name), "{c}");
            assert_eq!(lookup(name), Some(c), "{name}");
        }
        assert_eq!(lookup("no-break space"), Some('\u{A0}'));
        assert_eq!(lookup("ESC"), Some('\u{1B}'));
        assert_eq!(name_of('\u{1B}'), None);
        assert_eq!(lookup("NOT A NAME"), None);
    }
}
