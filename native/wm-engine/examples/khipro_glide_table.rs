//! Writes the Khipro glide table the data repository publishes: every word of
//! a Bangla word list with the keys that spell it on the Khipro grid
//! (`khipro_romanizer::spellings`), so the app reads them instead of working
//! them out on the phone, which is minutes of every core.
//!
//! gzcat bn_full.txt.gz | cargo run --release --example khipro_glide_table -- [--dark] | gzip -9 > table.txt.gz
//!
//! The list is read from stdin, a word per line (anything after the first
//! whitespace, a frequency, is ignored; `#` lines are comments). `--dark`
//! spells in Khipro Dark, which is `bn_khipro_dark_glide.txt.gz`; without it,
//! Classic, `bn_khipro_glide.txt.gz`. Lines are `word<TAB>spelling[<TAB>…]`,
//! in the list's order; a word with no spelling is left out.

use std::collections::HashSet;
use std::io::{self, BufRead, BufWriter, Write};
use std::thread;

use wm_engine::khipro::Variant;
use wm_engine::khipro_romanizer;

fn main() {
    let dark = std::env::args().skip(1).any(|a| a == "--dark");
    let variant = Variant::of(dark, false);
    let mut seen = HashSet::new();
    let words: Vec<String> = io::stdin()
        .lock()
        .lines()
        .map(|line| line.expect("word list reads"))
        .filter_map(|line| line.split_whitespace().next().map(str::to_string))
        .filter(|word| !word.starts_with('#') && seen.insert(word.clone()))
        .collect();
    khipro_romanizer::warm(variant);
    let cores = thread::available_parallelism().map(|n| n.get()).unwrap_or(4);
    let chunk = words.len().div_ceil(cores).max(1);
    let lines: Vec<Vec<String>> = thread::scope(|scope| {
        let workers: Vec<_> = words
            .chunks(chunk)
            .map(|part| {
                scope.spawn(move || {
                    part.iter()
                        .filter_map(|word| {
                            let spellings = khipro_romanizer::spellings(word, variant);
                            (!spellings.is_empty()).then(|| format!("{word}\t{}", spellings.join("\t")))
                        })
                        .collect::<Vec<_>>()
                })
            })
            .collect();
        workers.into_iter().map(|w| w.join().expect("worker finishes")).collect()
    });
    let edition = if dark { "Khipro Dark" } else { "Khipro Classic" };
    let mut out = BufWriter::new(io::stdout().lock());
    writeln!(out, "# {edition} spellings, for gliding on WM Keyboard's Khipro layout.").unwrap();
    writeln!(out, "# word<TAB>spelling[<TAB>spelling...]; generated by native/wm-engine/examples/khipro_glide_table.rs.")
        .unwrap();
    let mut spelled = 0;
    for line in lines.iter().flatten() {
        writeln!(out, "{line}").unwrap();
        spelled += 1;
    }
    out.flush().unwrap();
    eprintln!("{edition}: {} words, {spelled} spelled", words.len());
}
